/**
 * sol-load.js — ci-free component bootstrap.
 *
 * A single CLASSIC script (not a module) that does the one job
 * component-interop otherwise performs for a page: it injects the inline
 * import map that resolves the bare specifiers sol-components use
 * (`rdflib`, `sol-weather`, `sol-components/core/…`, …), then imports the
 * components the tag names. Everything resolves relative to wherever THIS
 * file was loaded from, so the same tag works from node_modules, a pod
 * copy, or a CDN — no local/cdn switch needed.
 *
 * Usage (the tag declares exactly what it loads):
 *
 *   <script src=".../sol-components/web/sol-load.js"
 *           data-components="sol-weather sol-time"></script>
 *
 *   <sol-weather source="weather-settings.ttl#Settings"></sol-weather>
 *
 * Place the tag BEFORE any `<script type="module">` that uses bare
 * specifiers — an import map is only accepted while none of its
 * specifiers have been resolved yet. Bundles: `sol-basic` (everyday UI,
 * incl. from-rdf menus), `sol-pod-bundle` (pod browsing),
 * `sol-form-bundle` (RDF editing).
 *
 * Also exposes `window.solLoad(name)` → the dynamic-import promise, for
 * late/conditional loads, and `window.solLoadReady` — a promise for the
 * components the tag itself named.
 *
 * Pages already running component-interop don't need this file; if both
 * are present, whichever injected an import map first wins (we skip
 * injection when an existing map already resolves `rdflib`).
 *
 * The MAP block below is GENERATED — regenerate with `npm run
 * build:importmaps` after adding a component or vendor dep.
 */
