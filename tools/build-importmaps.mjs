#!/usr/bin/env node
/**
 * build-importmaps.mjs
 *
 * Reads tools/external-deps.json + web/ and writes, into dist/:
 *   - importmap-cdn.json / importmap-local.json — bare specifiers → esm.sh URLs
 *     / ./vendor + ../web paths (for anyone consuming an importmap directly).
 *
 * It also REGENERATES the map baked into web/sol-load.js (the ci-free
 * bootstrap): the block between its generated-map markers gets the same
 * entries with package-root-relative paths, which sol-load absolutizes
 * against its own URL at runtime.
 *
 * The loader manifest ci reads (dist/sol-components.manifest.json) is
 * generated by tools/build-manifest.mjs from plugins/*.ttl (the RDF source
 * of truth). The vendored files are produced by tools/vendor.mjs.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here    = dirname(fileURLToPath(import.meta.url));
const root    = resolve(here, '..');
const outDir  = resolve(root, 'dist');
const webDir  = resolve(root, 'web');
const depsFile = resolve(here, 'external-deps.json');

const { deps } = JSON.parse(readFileSync(depsFile, 'utf8'));

const cdn   = { imports: {} };
const local = { imports: {} };
const baked = {};   // package-root-relative — baked into web/sol-load.js

// ── third-party deps (rdflib, dompurify, solid-ui, …) ────────────────────────
// All-ESM: bare `rdflib` resolves to ONE module, so every bundle shares one
// rdflib instance via the importmap itself — no window.$rdf UMD, no shim.
for (const [name, info] of Object.entries(deps)) {
  cdn.imports[name]   = info.cdn;
  const flat = name.replace(/\//g, '-');   // @scope/pkg → @scope-pkg
  local.imports[name] = `./vendor/${flat}.js`;
  baked[name]         = `dist/vendor/${flat}.js`;
  // A listed subpath resolves to the same vendored file (one shared instance).
  for (const sub of info.subpaths || []) {
    cdn.imports[`${name}/${sub}`]   = `${info.cdn}/${sub}`;
    local.imports[`${name}/${sub}`] = `./vendor/${flat}.js`;
    baked[`${name}/${sub}`]         = `dist/vendor/${flat}.js`;
  }
}

// ── swc components — one BARE specifier per web/ module ──────────────────────
// So any app importing 'sol-time' (or a loader loading it) resolves to the
// source ESM. Components import their own deps (rdflib via core/rdf, etc.)
// through the entries above. local → repo source; cdn → esm.sh.
// sol-load itself stays out: it's the classic bootstrap script, not a module.
const PKG = 'sol-components';
const components = readdirSync(webDir)
  .filter((f) => /^[a-z][a-z0-9-]*\.js$/.test(f))   // top-level modules only
  .map((f) => f.replace(/\.js$/, ''))
  .filter((c) => c !== 'sol-load');
for (const c of components) {
  local.imports[c] = `../web/${c}.js`;               // dist/ → ../web (repo source)
  cdn.imports[c]   = `https://esm.sh/${PKG}/web/${c}.js`;
  baked[c]         = `web/${c}.js`;
}
// rdf-bundle — the editing-stack barrel in core/. The ci manifest exposes it
// under this importmap name (a shared-modules entry); keep sol-load and the
// standalone importmaps in parity so `data-components="rdf-bundle"` works
// with either loader.
local.imports['rdf-bundle'] = '../core/rdf-bundle.js';
cdn.imports['rdf-bundle']   = `https://esm.sh/${PKG}/core/rdf-bundle.js`;
baked['rdf-bundle']         = 'core/rdf-bundle.js';

// swc-source prefixes for app bundles that import internals (core/, sources/).
for (const sub of ['core/', 'sources/', 'data/']) {
  local.imports[`${PKG}/${sub}`] = `../${sub}`;
  cdn.imports[`${PKG}/${sub}`]   = `https://esm.sh/${PKG}/${sub}`;
  baked[`${PKG}/${sub}`]         = sub;
}
local.imports[`${PKG}/`] = '../web/';
cdn.imports[`${PKG}/`]   = `https://esm.sh/${PKG}/web/`;
baked[`${PKG}/`]         = 'web/';

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, 'importmap-cdn.json'),   JSON.stringify(cdn,   null, 2) + '\n');
writeFileSync(resolve(outDir, 'importmap-local.json'), JSON.stringify(local, null, 2) + '\n');

console.log(`[build-importmaps] wrote dist/importmap-cdn.json   (${Object.keys(cdn.imports).length} entries)`);
console.log(`[build-importmaps] wrote dist/importmap-local.json (${Object.keys(local.imports).length} entries)`);

// ── bake the package-root-relative map into web/sol-load.js ──────────────────
const loaderFile = resolve(webDir, 'sol-load.js');
const loaderSrc  = readFileSync(loaderFile, 'utf8');
const START = '/* ── generated by tools/build-importmaps.mjs — do not edit by hand ── */';
const END   = '/* ── end generated map ── */';
const start = loaderSrc.indexOf(START), end = loaderSrc.indexOf(END);
if (start === -1 || end === -1) {
  throw new Error('[build-importmaps] web/sol-load.js is missing its generated-map markers');
}
const updated = loaderSrc.slice(0, start + START.length)
  + `\n  var MAP = ${JSON.stringify(baked, null, 4).replace(/\n/g, '\n  ')};\n  `
  + loaderSrc.slice(end);
writeFileSync(loaderFile, updated);
console.log(`[build-importmaps] baked ${Object.keys(baked).length} entries into web/sol-load.js`);
